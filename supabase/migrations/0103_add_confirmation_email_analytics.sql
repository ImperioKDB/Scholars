-- Track confirmation-email requests made by Scholars so admins can distinguish
-- accepted Auth requests, failed requests, and accounts that later confirmed.
-- Provider delivery is still ultimately reported by Supabase/Brevo; this table
-- deliberately labels the accepted state rather than claiming inbox delivery.
create table if not exists public.auth_confirmation_email_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email_hash text not null,
  email_domain text not null,
  request_kind text not null check (request_kind in ('signup', 'resend')),
  request_status text not null check (request_status in ('accepted', 'failed')),
  error_code text,
  requested_at timestamptz not null default now()
);

create index if not exists auth_confirmation_email_events_requested_at_idx
  on public.auth_confirmation_email_events (requested_at desc);
create index if not exists auth_confirmation_email_events_user_id_idx
  on public.auth_confirmation_email_events (user_id);
create index if not exists auth_confirmation_email_events_email_hash_idx
  on public.auth_confirmation_email_events (email_hash);

alter table public.auth_confirmation_email_events enable row level security;

drop policy if exists auth_confirmation_email_events_select_admin
  on public.auth_confirmation_email_events;
create policy auth_confirmation_email_events_select_admin
  on public.auth_confirmation_email_events
  for select using (public.is_admin(auth.uid()));

create or replace function public.get_auth_confirmation_email_analytics(
  p_since timestamptz,
  p_until timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $function$
declare
  v_summary jsonb;
  v_daily jsonb;
  v_recent jsonb;
begin
  if p_since is null or p_until is null or p_since >= p_until then
    raise exception 'Invalid confirmation analytics range';
  end if;

  if not public.is_admin(auth.uid()) then
    raise exception using errcode = '42501', message = 'Admin access required';
  end if;

  with scoped as (
    select e.request_status, u.email_confirmed_at
    from public.auth_confirmation_email_events e
    left join auth.users u on u.id = e.user_id
    where e.requested_at >= p_since and e.requested_at < p_until
  ), counts as (
    select
      count(*) filter (where request_status = 'accepted')::int as accepted,
      count(*) filter (where request_status = 'failed')::int as failed,
      count(*) filter (where request_status = 'accepted' and email_confirmed_at is not null)::int as confirmed
    from scoped
  )
  select jsonb_build_object(
    'accepted', accepted,
    'failed', failed,
    'confirmed', confirmed,
    'pending', greatest(accepted - confirmed, 0),
    'confirmation_rate', case when accepted = 0 then 0 else round((confirmed::numeric / accepted::numeric) * 100, 1) end
  ) into v_summary
  from counts;

  with days as (
    select
      date_trunc('day', e.requested_at)::date as day,
      count(*) filter (where e.request_status = 'accepted')::int as accepted,
      count(*) filter (where e.request_status = 'failed')::int as failed,
      count(*) filter (where e.request_status = 'accepted' and u.email_confirmed_at is not null)::int as confirmed
    from public.auth_confirmation_email_events e
    left join auth.users u on u.id = e.user_id
    where e.requested_at >= p_since and e.requested_at < p_until
    group by 1
    order by 1
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'day', day,
    'accepted', accepted,
    'failed', failed,
    'confirmed', confirmed
  )), '[]'::jsonb) into v_daily
  from days;

  select coalesce(jsonb_agg(row_data order by requested_at desc), '[]'::jsonb)
  into v_recent
  from (
    select
      e.requested_at,
      jsonb_build_object(
        'id', e.id,
        'requested_at', e.requested_at,
        'request_kind', e.request_kind,
        'request_status', e.request_status,
        'email_domain', e.email_domain,
        'error_code', e.error_code,
        'confirmed', (u.email_confirmed_at is not null),
        'confirmed_at', u.email_confirmed_at
      ) as row_data
    from public.auth_confirmation_email_events e
    left join auth.users u on u.id = e.user_id
    where e.requested_at >= p_since and e.requested_at < p_until
    order by e.requested_at desc
    limit 100
  ) recent_rows;

  return jsonb_build_object(
    'summary', v_summary,
    'daily', v_daily,
    'recent', v_recent
  );
end;
$function$;

revoke all on function public.get_auth_confirmation_email_analytics(timestamptz, timestamptz) from public;
grant execute on function public.get_auth_confirmation_email_analytics(timestamptz, timestamptz) to authenticated;

comment on table public.auth_confirmation_email_events is
  'Admin-only operational record of confirmation email requests. accepted means Supabase Auth accepted the request; it is not an inbox-delivery guarantee.';

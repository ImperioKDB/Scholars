export const INSTITUTIONS: Institution[] = [
  ...FEDERAL_UNIVERSITIES.map((name) => ({ name, type: "federal_uni" as const })),
  ...STATE_UNIVERSITIES.map((name) => ({ name, type: "state_uni" as const })),
  ...PRIVATE_UNIVERSITIES.map((name) => ({ name, type: "private_uni" as const })),
  ...POLYTECHNICS.map((name) => ({ name, type: "polytechnic" as const })),
  ...COLLEGES_OF_EDUCATION.map((name) => ({ name, type: "college_of_education" as const })),
].sort((a, b) => a.name.localeCompare(b.name));

const TYPE_LABELS: Record<InstitutionType, string> = {
  federal_uni: "Federal University",
  state_uni: "State University",
  private_uni: "Private University",
  polytechnic: "Polytechnic",
  college_of_education: "College of Education",
};

export const INSTITUTION_OPTIONS = INSTITUTIONS.map((i) => ({
  value: i.name,
  label: i.name,
  sublabel: TYPE_LABELS[i.type],
}));

export function institutionTypeFor(name: string): InstitutionType | null {
  return INSTITUTIONS.find((i) => i.name === name)?.type ?? null;
}
